/**
 * Per-mission fact blocks with rule-based flags (rules published in FLAG_RULES), generated from the raw audit files.
 * Used by summarize.ts; produces generated_missions.md.
 */
import type {RunResult} from './campaignAudit';
import type {PlanResult} from './expertPlanner';
import type {MissionMetrics} from './difficultyIndex';

type Row = MissionMetrics & {ddi:{total:number;parts:{P:number;W:number;N:number;C:number}}};
type Plan = PlanResult & {candidate:string};
type Pair = {a:string;b:string;gridIoU:number};

export const FLAG_RULES = [
  '- **RUN-DOMINANT**: the fastest expert plan is Run and no Sneak plan clears unseen.',
  '- **TIGHT**: median bottleneck window ≤ 13 % (at most 1 of the 8 wait options stays unseen at the hardest segment).',
  '- **SPIKE / DIP**: DDI at least 20 above / below the previous mission in campaign order.',
  '- **ESCAPE-GATED**: at least 2 Sneak/Walk expert plans fail after the pickup (escape phase).',
  '- **RISK-ROUTE-BLOCKED**: no expert plan of any gait clears on the authored risk route (route 1).',
  '- **MIRROR of X**: walkable grid identical to mission X under a mirror transform (IoU = 1).',
  '- **NAIVE-ZERO**: none of the 54 reactive-bot runs clears.',
].join('\n');

const pct=(v:number)=>Number.isFinite(v)?`${Math.round(v*100)}%`:'N/A';
const f=(v:number|null|undefined,d=1)=>v===null||v===undefined||!Number.isFinite(v)?'N/A':v.toFixed(d);

export function missionNotes(rows:Row[], plans:Plan[], runs:RunResult[], pairs:Pair[]):string {
  const out:string[]=['<!-- generated by tools/gameplay-audit/missionNotes.ts — do not edit by hand -->',''];
  rows.forEach((m,i)=>{
    const ps=plans.filter(p=>p.candidate==='A'&&p.id===m.id), rs=runs.filter(r=>r.candidate==='A'&&r.id===m.id);
    const prev=i>0?rows[i-1]:null;
    const flags:string[]=[];
    const sneakUnseen=ps.some(p=>p.gait==='sneak'&&p.clear&&p.unseen);
    if (m.fastestGait==='run'&&!sneakUnseen) flags.push('RUN-DOMINANT');
    if (m.expertClear>0&&m.bottleneckWindow<=0.13) flags.push('TIGHT');
    if (prev&&m.ddi.total-prev.ddi.total>=20) flags.push(`SPIKE (+${m.ddi.total-prev.ddi.total} vs ${prev.id})`);
    if (prev&&prev.ddi.total-m.ddi.total>=20) flags.push(`DIP (−${prev.ddi.total-m.ddi.total} vs ${prev.id})`);
    // a plan failed in the escape when every attempt's furthest segment lies beyond the approach length
    const pastPickup=(cause:string)=>{const m=[...cause.matchAll(/@(\d+)\/\d+\(approach (\d+)\)/g)];return m.length>0&&m.every(x=>+x[1]>+x[2]);};
    const escFails=ps.filter(p=>(p.gait==='sneak'||p.gait==='walk')&&!p.clear&&pastPickup(p.failCause??'')).length;
    if (escFails>=2) flags.push('ESCAPE-GATED');
    if (!ps.some(p=>p.route===1&&p.clear)) flags.push('RISK-ROUTE-BLOCKED');
    for (const p of pairs) if (p.gridIoU===1&&(p.a===m.id||p.b===m.id)) flags.push(`MIRROR of ${p.a===m.id?p.b:p.a}`);
    if (m.reactiveClearRate===0) flags.push('NAIVE-ZERO');
    out.push(`### ${m.id} ${m.title} (${m.theme}) — DDI ${m.ddi.total}`,'');
    out.push(`- 구조: 바닥 ${m.floorCells}칸, 경비 ${m.guards}, CCTV ${m.cameras}, 문 ${m.doors}, 차단 소품 ${m.blockingProps}. 최단 접근 ${f(m.shortestApproachTiles,0)}타일 / 안전 경로 ${f(m.safeRouteTiles,0)} / 위험 경로 ${f(m.riskRouteTiles,0)}, 빠른 탈출 ${f(m.quickEscapeTiles,0)} / 대체 탈출 ${f(m.altEscapeTiles,0)}.`);
    out.push(`- 감시: 접근 경로 평균 감시율 ${pct(m.routeWatched)}, 한 번이라도 보이는 구간 ${pct(m.routeEverWatched)}, 위험 구간 ${m.dangerSections}개, 시야 중첩 샘플 ${m.overlapSamples}, 빠른 탈출 감시율 ${pct(m.escapeWatched)}.`);
    const cell=(g:string,r:number)=>{const p=ps.find(x=>x.gait===g&&x.route===r);if(!p)return 'N/A';return p.clear?`${p.unseen?'무발각':'발각 후'} ${f(p.seconds)}s(대기 ${f(p.waitSeconds)})`:'실패';};
    out.push(`- 전문가(상한): 안전 경로 — S ${cell('sneak',0)} · W ${cell('walk',0)} · R ${cell('run',0)} · M ${cell('mixed',0)}; 위험 경로 — S ${cell('sneak',1)} · W ${cell('walk',1)} · R ${cell('run',1)} · M ${cell('mixed',1)}. 병목 창 ${pct(m.bottleneckWindow)}.`);
    const strat=[...new Set(rs.map(r=>r.strategy))].map(s=>{const x=rs.filter(r=>r.strategy===s);return `${s} ${x.filter(r=>r.clear).length}/${x.length}`;}).join(', ');
    const causes:Record<string,number>={}; for (const r of rs) if (!r.clear) causes[r.outcome]=(causes[r.outcome]??0)+1;
    out.push(`- 반응형 봇: ${strat}. 실패 원인 ${Object.entries(causes).map(([k,v])=>`${k} ${v}`).join(', ')||'없음'}. 출발 지연에 따라 결과가 바뀐 전략·경로 조합 ${pct(m.reactiveDelaySensitivity)}.`);
    out.push(`- 플래그: ${flags.join(' · ')||'없음'}`,'');
  });
  out.push('#### 플래그 규칙','',FLAG_RULES,'');
  return out.join('\n');
}
